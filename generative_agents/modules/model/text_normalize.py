# OpenCC 單例（惰性初始化）
_opencc = None
_opencc_failed = False

# fallback 替換表快取
_fallback_table: dict[str, str] | None = None


def _get_opencc():
    """惰性初始化 OpenCC('s2hk') 單例；失敗時返回 None（降級 fallback）。"""
    global _opencc, _opencc_failed
    if _opencc is not None or _opencc_failed:
        return _opencc
    try:
        from opencc import OpenCC
        _opencc = OpenCC("s2hk")
    except Exception as e:  # noqa: BLE001 — 永不拋異常
        logger.warning("OpenCC 初始化失敗，normalize 降級為 fallback dict: %s", e)
        _opencc_failed = True
        _opencc = None
    return _opencc


def build_fallback_dict(glossary_path: str = "data/glossary_s2hk.json") -> dict[str, str]:
    """由機讀 glossary JSON 建立 fallback 替換表。

    合併 keywords / place_names / agent_names / vocabulary 四段，
    再疊加內置高頻簡繁字對表。檔案唔存在或解析失敗時返回內置表。
    """
    table: dict[str, str] = dict(_FALLBACK_CHARS)
    try:
        if os.path.exists(glossary_path):
            with open(glossary_path, "r", encoding="utf-8") as f:
                glossary = json.load(f)
            for section in ("keywords", "place_names", "agent_names", "vocabulary"):
                mapping = glossary.get(section)
                if isinstance(mapping, dict):
                    table.update({str(k): str(v) for k, v in mapping.items()})
    except Exception as e:  # noqa: BLE001
        logger.warning("讀取 glossary fallback dict 失敗（%s）: %s", glossary_path, e)
    return table


def _get_fallback_table() -> dict[str, str]:
    global _fallback_table
    if _fallback_table is None:
        _fallback_table = build_fallback_dict()
    return _fallback_table


def _fallback_convert(text: str) -> str:
    """fallback：先逐詞替換（長詞優先），再逐字替換。"""
    table = _get_fallback_table()
    words = sorted((k for k in table if len(k) > 1), key=len, reverse=True)
    for word in words:
        if word in text:
            text = text.replace(word, table[word])
    return "".join(table.get(c, c) for c in text)


def normalize_text(text: str) -> str:
    """將字串中嘅簡體中文轉為繁體香港字形（s2hk）。

    - 空串／純英文／純數字原樣返回（fast path：無 CJK 字符直接 return）
    - 永不拋異常：任何內部錯誤 log warning 後返回原文
    """
    if not isinstance(text, str) or not text:
        return text
    if not _CJK_RE.search(text):
        return text
    try:
        cc = _get_opencc()
        if cc is not None:
            return cc.convert(text)
        return _fallback_convert(text)
    except Exception as e:  # noqa: BLE001
        logger.warning("normalize_text 失敗，返回原文: %s", e)
        return text


def normalize_llm_output(output: Any, return_type: type | None = None) -> Any:
    """對 LLMModel._completion 嘅輸出做遞歸 normalize。

    - str → normalize_text
    - list / tuple → 逐項遞歸（保持容器型別）
    - dict → 只 normalize value，key 不郁
    - 其他型別（int/bool/None）原樣返回
    喺 LLMModel.completion() 內、callback 之前調用。
    """
    try:
        return _normalize(output)
    except Exception as e:  # noqa: BLE001
        logger.warning("normalize_llm_output 失敗，返回原輸出: %s", e)
        return output


def _normalize(value: Any) -> Any:
    if isinstance(value, str):
        return normalize_text(value)
    if isinstance(value, list):
        return [_normalize(v) for v in value]
    if isinstance(value, tuple):
        return tuple(_normalize(v) for v in value)
    if isinstance(value, dict):
        return {k: _normalize(v) for k, v in value.items()}
    return value


def contains_simplified(text: str) -> bool:
    """黑名單掃描：text 含常見簡體字即返回 True。

    供 checkpoint 載入 warning 同端到端冒煙測試用。
    """
    if not isinstance(text, str) or not text:
        return False
    try:
        return any(c in _SIMPLIFIED_SET for c in text)
    except Exception:  # noqa: BLE001
        return False
